// Machine-local only (never committed): private/symbolic/<sf symbol name>.svg
const files = import.meta.glob("/private/symbolic/*.svg", { eager: true, query: "?url", import: "default" }) as Record<string, string>;
const BY_NAME: Record<string, string> = {};
for (const [path, url] of Object.entries(files)) {
  const m = path.match(/symbolic\/(.+)\.svg$/);
  if (m) BY_NAME[m[1]] = url;
}

export const SYMBOLIC_AVAILABLE = Object.keys(BY_NAME).length > 0;

export function symbolicUrl(icon: string): string | null {
  const name = SYMBOLIC[icon];
  return name ? (BY_NAME[name] ?? null) : null;
}

/** Every symbol name the map uses, for the export. */
export function symbolicNames(): string[] {
  return [...new Set([...Object.values(SYMBOLIC), ...Object.values(SYMBOLIC_PRODUCT)])].sort();
}

export function symbolicProductUrl(product: string): string | null {
  const name = SYMBOLIC_PRODUCT[product];
  return name ? (BY_NAME[name] ?? null) : null;
}

/** Apple's system colours for product tiles, so each one keeps a colour of its own. */
const TILE: Record<string, string> = {
  home: "#007AFF", checklist: "#34C759", calendar: "#FF3B30", inbox: "#0A84FF", claude: "#D97757", settings: "#8E8E93",
  folder: "#5AC8FA", graduation: "#5856D6", document: "#007AFF", pages: "#007AFF", spreadsheet: "#34C759", presentation: "#FF9500",
  drawing: "#AF52DE", gallery: "#FF2D55", project: "#5AC8FA", mail: "#007AFF", heart: "#FF2D55", wallet: "#34C759",
};
const PALETTE = ["#FF3B30", "#FF9500", "#FFCC00", "#34C759", "#00C7BE", "#30B0C7", "#007AFF", "#5856D6", "#AF52DE", "#FF2D55", "#A2845E"];
export function tileColor(product: string): string {
  if (TILE[product]) return TILE[product];
  let h = 0;
  for (let i = 0; i < product.length; i++) h = (h * 31 + product.charCodeAt(i)) >>> 0;
  return PALETTE[h % PALETTE.length];
}
