// Machine-local only (never committed): private/symbolic/<sf symbol name>.svg
const files = import.meta.glob("/private/symbolic/*.svg", { eager: true, query: "?url", import: "default" }) as Record<string, string>;
const BY_NAME: Record<string, string> = {};
for (const [path, url] of Object.entries(files)) {
  const m = path.match(/symbolic\/(.+)\.svg$/);
  if (m) BY_NAME[m[1]] = url;
}

export const SYMBOLIC_AVAILABLE = Object.keys(BY_NAME).length > 0;

export function symbolicUrl(icon: string): string | null {
  const name = SYMBOLIC[icon];
  return name ? (BY_NAME[name] ?? null) : null;
}

/** Every symbol name the map uses, for the export. */
export function symbolicNames(): string[] {
  return [...new Set(Object.values(SYMBOLIC))].sort();
}
